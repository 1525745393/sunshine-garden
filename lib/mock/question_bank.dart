/// 获取指定学段的关卡列表（含题目）
List<Level> levelsForStage(String stage) {
  return switch (stage) {
    'kindergarten' => _kindergartenLevels,
    'middle' => _middleLevels,
    _ => _primaryLevels,
  };
}

